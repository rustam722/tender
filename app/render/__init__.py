"""Отрисовка документов пакета: контекст, Word, книга Excel, сборка.

Здесь живёт только то, что нужно сразу нескольким модулям отрисовки: причина,
по которой файл не удалось сохранить, и пометка пустого значения.
"""
import errno


class Blank(str):
    """Пустое значение контекста, помнящее, из какого поля оно пришло.

    Пустая строка в тексте документа ничего о себе не говорит: собранная
    заявка уходила с четырьмя пустыми строками банковских реквизитов, и
    узнавал об этом человек от закупочной комиссии. Поэтому на время
    отрисовки Word пустое значение несёт с собой путь (`org.bank_name`):
    напечатали пустоту -- значит есть что сказать (app.render.docx_render).

    Ведёт себя как пустая строка, в которую превратилась бы и так: ложна в
    условиях (`{{ a or b }}` берёт b), сравнивается с «» и печатается
    пустотой. Любая операция над ней (сложение, .strip(), format) даёт
    обычную строку и пометку теряет -- значит пустота, прошедшая через
    функцию шаблона, не видна; `date_ru`/`date_long` отдают её как есть
    именно поэтому.
    """
    __slots__ = ("path",)

    def __new__(cls, value: object, path: str):
        blank = super().__new__(cls, "" if value is None else value)
        blank.path = path
        return blank

# Windows: запись в файл, занятый Word или Excel, -- тоже PermissionError, и от
# «нет прав на папку» её отличает только код ОС. 32 -- ERROR_SHARING_VIOLATION,
# 33 -- ERROR_LOCK_VIOLATION. На других системах winerror у исключения нет.
_SHARING = (32, 33)


def save_cause(exc: OSError) -> str:
    """Почему файл не сохранился -- то, что ОС действительно сказала.

    Раньше любой OSError получал подсказку «проверьте, что файл не открыт
    в Word»: человек шёл закрывать Word, которого не открывал, а дело было
    в месте на диске или в правах на папку. Что можно отличить -- отличаем,
    остальное не называем причиной, а перечисляем честно. Код ОС и английский
    текст наружу не уходят: наружу уходит русская фраза.
    """
    if exc.errno == errno.ENOSPC:
        return ("на диске не осталось места. Освободите место и соберите "
                "пакет заново.")
    if getattr(exc, "winerror", None) in _SHARING:
        return ("файл открыт в другой программе (чаще всего в Word или "
                "Excel). Закройте его и соберите пакет заново.")
    if isinstance(exc, PermissionError):
        return ("в эту папку нельзя записывать или файл защищён от записи. "
                "Проверьте права на папку или выберите другую папку.")
    if isinstance(exc, FileNotFoundError):
        return "папки для него больше нет. Проверьте путь к папке пакета."
    return ("записать его не удалось: проверьте, что файл не открыт в другой "
            "программе, что в папку можно записывать и что на диске есть "
            "место.")
