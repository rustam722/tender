"""Сторож на весь набор: рабочая база фирмы для тестов закрыта.

Набор тестов работает только на временных базах (`tmp_path`). Рабочая база --
`data/tender.db` рядом с программой, и на машине фирмы в ней лежат её
организации, сотрудники, МТР, опыт и профили заказчиков.

Чем опасен тест, который до неё дотянется. `db.connect` сам создаёт папку
`data` и файл, `migrate` пишет схему, а наполнение по непустой базе молчит --
поэтому данные фирмы такой тест, скорее всего, не испортит. Испортит он другое:
на машине фирмы база окажется созданной и засеянной тестом (человек решит, что
программа уже настроена), а сам тест станет зависеть от того, что лежит
в чужой базе, то есть ненадёжным.

Дверей к ней две: `fill_references(DB_PATH)` и `create_app(DB_PATH)` -- и до
этого сторожа их охранял комментарий в одном тесте, который объяснял одну.
Поэтому сторож стоит не в тесте, а здесь: он включается сам на каждом тесте
набора, и забыть его нельзя.

Смотрит он на ПУТЬ, а не на имя: модуль может взять `DB_PATH` копией имени, и
подмена `config.DB_PATH` до него не дойдёт. Настоящий путь запоминается при
загрузке этого файла -- тест, подменивший `config.DB_PATH` на временный,
рабочую базу этим не открывает.

Чего он не поймает: соединение, открытое в обход `app.db.connect` -- модулем,
который возьмёт `connect` копией имени (`from app.db import connect`), или
прямым вызовом `sqlite3.connect`. Сегодня так не делает никто: и приложение,
и наполнение справочников зовут `db.connect` через модуль.
"""
from pathlib import Path

import pytest

from app import config, db

WORKING_DB = Path(config.DB_PATH)


@pytest.fixture(autouse=True)
def no_writes_to_the_working_database(monkeypatch):
    real_connect = db.connect

    def connect(path, *args, **kwargs):
        if Path(path) == WORKING_DB or Path(path).resolve() == WORKING_DB.resolve():
            # pytest.fail, а не assert: его исключение не Exception, и его
            # не проглотит ни один `except Exception` внутри программы.
            pytest.fail(
                "Тест открывает рабочую базу программы "
                f"({WORKING_DB}): на машине фирмы в ней её справочники. "
                "Передайте тесту временный путь (tmp_path) -- например, "
                "main(db_path=tmp_path / \"t.db\") -- или подмените "
                "app.db.connect.")
        return real_connect(path, *args, **kwargs)

    monkeypatch.setattr(db, "connect", connect)
